/**
 * El ícono de una `iconKey`. Si no hay entrada usa `fallback` (cada superficie pasa el suyo,
 * como las tres laterales tenían el propio: InboxIcon en admin, InicioIcon en colegio/padre).
 * Sin `fallback` (p. ej. los hijos del padre, que hoy no llevan ícono) devuelve `null`.
 */
export function IconoNav({
    clave,
    className = "",
    fallback,
}: {
    clave: string;
    className?: string;
    fallback?: IconoNavComponente;
}): JSX.Element | null {
    const Icono = ICONOS_NAV[clave] ?? fallback;
    return Icono ? <Icono className={className} /> : null;
}

export function tieneIcono(clave: string): boolean {
    return clave in ICONOS_NAV;
}
